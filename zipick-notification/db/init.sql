-- =============================================================================
-- ZIPICK 알림센터 DB (zipick_notification) 초기화 DDL
-- =============================================================================
-- 메인 DB(zipick)와 다른 데이터베이스를 쓴다. 알림센터는 메인의 테이블을 읽지 않는다 (user_id 숫자만 받는다).
--
--   CREATE DATABASE zipick_notification;        -- 한 번
--   psql -U {사용자} -d zipick_notification -f zipick-notification/db/init.sql
--
-- [경고] 기존 테이블을 DROP 한다. 로컬에서만 그대로 쓰고, 운영은 변경분만 적용한다.
-- 테이블을 바꾸면 이 파일과 각 패키지의 SQL(scan/insert)을 같이 고친다. 서버는 기동할 때 스키마를 검증하지 않는다.
-- =============================================================================

DROP TABLE IF EXISTS notification_messages;
DROP TABLE IF EXISTS campaigns;
DROP TABLE IF EXISTS subscriptions;
DROP TABLE IF EXISTS notification_templates;

-- 템플릿: 코드별 문구. {{변수}} 자리를 요청의 변수로 채운다
create table notification_templates (
    enabled boolean not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    category varchar(20) not null check (category in ('TRANSACTIONAL','INFORMATIONAL','MARKETING')),
    code varchar(60) not null,
    name varchar(100) not null,
    description varchar(300),
    title_template varchar(300) not null,
    url_template varchar(500),
    body_template text not null,
    primary key (id),
    constraint uk_template_code unique (code)
);

-- 수신 정보·동의: 메인 서버의 user_id 기준
create table subscriptions (
    enabled boolean not null,
    marketing_consent boolean not null,
    new_match_enabled boolean not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    marketing_consented_at timestamp(6),
    updated_at timestamp(6),
    user_id bigint not null,
    deadline_days varchar(50) not null,
    email varchar(255),
    slack_webhook_url varchar(500),
    primary key (id),
    constraint uk_subscription_user unique (user_id)
);

-- 예약 발송
create table campaigns (
    queued_count integer not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    queued_at timestamp(6),
    scheduled_at timestamp(6) not null,
    updated_at timestamp(6),
    status varchar(20) not null check (status in ('SCHEDULED','QUEUED','CANCELLED')),
    audience varchar(30) not null check (audience in ('MARKETING_CONSENTED','ENABLED','USER_IDS')),
    template_code varchar(60) not null,
    created_by varchar(100),
    name varchar(100) not null,
    user_ids text,
    variables text,
    primary key (id)
);

-- 아웃박스
create table notification_messages (
    attempts integer not null,
    campaign_id bigint,
    created_at timestamp(6),
    id bigint generated by default as identity,
    scheduled_for timestamp(6) not null,
    sent_at timestamp(6),
    updated_at timestamp(6),
    user_id bigint,
    category varchar(20) not null check (category in ('TRANSACTIONAL','INFORMATIONAL','MARKETING')),
    status varchar(20) not null check (status in ('PENDING','SENT','FAILED','SKIPPED','CANCELLED')),
    channels varchar(50),
    template_code varchar(60) not null,
    dedupe_key varchar(120),
    to_email varchar(255),
    title varchar(300) not null,
    last_error varchar(500),
    to_slack_webhook_url varchar(500),
    url varchar(500),
    body text not null,
    variables text,
    primary key (id),
    constraint uk_message_dedupe unique (dedupe_key)
);

create index idx_campaign_status on campaigns (status, scheduled_at);
create index idx_message_status on notification_messages (status, scheduled_for);
create index idx_message_user on notification_messages (user_id, id);
