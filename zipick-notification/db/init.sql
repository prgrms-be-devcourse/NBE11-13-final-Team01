-- =============================================================================
-- ZIPICK 알림센터 DB (zipick_notification) 초기화 DDL  — 순수 전송 버전 (2026-10-23)
-- =============================================================================
-- 메인 DB(zipick)와 다른 데이터베이스를 쓴다. 알림센터는 사용자·설정·동의를 모른다.
-- 템플릿은 DB 가 아니라 저장소의 templates/*.yaml 에 있다.
--
--   CREATE DATABASE zipick_notification;        -- 한 번
--   psql -U {사용자} -d zipick_notification -f zipick-notification/db/init.sql
--
-- [경고] 기존 테이블을 DROP 한다. 로컬에서만 그대로 쓰고, 운영은 변경분만 적용한다.
-- 테이블을 바꾸면 이 파일과 각 패키지의 SQL(scan/insert)을 같이 고친다. 서버는 기동할 때 스키마를 검증하지 않는다.
-- =============================================================================

DROP TABLE IF EXISTS notification_deliveries;
DROP TABLE IF EXISTS notification_messages;
DROP TABLE IF EXISTS notification_batches;
-- 이전 버전(알림센터가 설정·템플릿·캠페인을 가졌을 때)의 테이블
DROP TABLE IF EXISTS campaigns;
DROP TABLE IF EXISTS subscriptions;
DROP TABLE IF EXISTS notification_templates;

-- 묶음 요청: 같은 템플릿·채널·시각으로 수신자 여러 명. 대상은 요청하는 쪽이 정해서 보낸다
create table notification_batches (
    id bigint generated by default as identity,
    source varchar(40) not null,
    template_code varchar(60) not null,
    channels varchar(50) not null,
    scheduled_for timestamp(6) not null,
    status varchar(20) not null check (status in ('SCHEDULED','CANCELLED')),
    tags jsonb not null default '{}',
    skipped_duplicates integer not null default 0,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

-- 아웃박스: 요청 하나. 문구는 요청 시점에 채워 저장한다 (예약 중 템플릿이 바뀌어도 요청 당시 문구로 나감)
create table notification_messages (
    id bigint generated by default as identity,
    source varchar(40) not null,
    template_code varchar(60) not null,
    batch_id bigint references notification_batches (id),
    dedupe_key varchar(120),
    channels varchar(50) not null,
    to_email varchar(255),
    to_slack_webhook_url varchar(500),
    address_masked boolean not null default false,
    variables text not null,
    missing_variables text not null default '',
    email_subject varchar(300),
    email_body text,
    slack_text text,
    tags jsonb not null default '{}',
    scheduled_for timestamp(6) not null,
    status varchar(20) not null check (status in ('PENDING','SENT','PARTIAL','FAILED','CANCELLED')),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_message_dedupe unique (dedupe_key)
);

-- 채널별 발송 기록: 메시지 × 채널. 채널마다 따로 재시도하고, 성공한 채널로는 다시 보내지 않는다
create table notification_deliveries (
    id bigint generated by default as identity,
    message_id bigint not null references notification_messages (id) on delete cascade,
    channel varchar(20) not null,
    status varchar(20) not null check (status in ('PENDING','SENT','FAILED')),
    attempts integer not null default 0,
    last_error varchar(500),
    sent_at timestamp(6),
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_delivery_message_channel unique (message_id, channel)
);

create index idx_message_status on notification_messages (status, scheduled_for);
create index idx_message_batch on notification_messages (batch_id);
create index idx_message_tags on notification_messages using gin (tags);
create index idx_message_source_created on notification_messages (source, created_at);
create index idx_batch_status on notification_batches (status, scheduled_for);
