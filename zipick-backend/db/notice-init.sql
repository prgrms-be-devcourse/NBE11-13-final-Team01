create table housing_supply_condition (
    housing_supply_condition_id bigint generated by default as identity,
    housing_supply_id bigint not null,
    condition_code varchar(100) not null,
    condition_name varchar(300) not null,
    rent_deposit bigint,
    monthly_rent bigint,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    raw_payload jsonb,
    primary key (housing_supply_condition_id),
    constraint uk_housing_supply_condition unique (housing_supply_id, condition_code),
    constraint fk_housing_supply_condition_supply foreign key (housing_supply_id)
        references housing_supply (housing_supply_id) on delete cascade
);

create table document_parse_history (
    document_parse_history_id bigint generated by default as identity,
    document_key varchar(700) not null,
    parser_version varchar(100) not null,
    parse_status varchar(30) not null,
    parsed_unit_count integer not null default 0,
    file_size bigint,
    parsed_at timestamp(6) with time zone not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (document_parse_history_id),
    constraint uk_document_parse_history_key unique (document_key, parser_version)
);

-- Lite 추출 성공 여부와 별도로 3.8 Flash 정규화 재시도를 보존한다.
create table ai_normalization_job (
    attempt_count integer not null default 0,
    ai_normalization_job_id bigint generated by default as identity,
    created_at timestamp(6) not null,
    next_retry_at timestamp(6) with time zone,
    normalized_at timestamp(6) with time zone,
    updated_at timestamp(6) not null,
    source varchar(30) not null,
    normalization_status varchar(30) not null,
    input_hash varchar(64) not null,
    normalizer_version varchar(100) not null,
    document_id varchar(150) not null,
    notice_title varchar(500),
    input_payload text not null,
    last_error text,
    primary key (ai_normalization_job_id),
    constraint uk_ai_normalization_job_source_document unique (source, document_id)
);

