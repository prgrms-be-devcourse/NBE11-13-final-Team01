-- =============================================================================
-- ZIPICK 주변 생활 인프라 로컬 PostgreSQL DDL
-- =============================================================================
--
-- [실행 순서] local-init.sql → notice-init.sql → infra-init.sql
--   이 스크립트는 notice-init.sql 이 만든 housing 테이블을 참조하므로 반드시 뒤에 실행한다.
--
--   psql -U {사용자명} -d zipick -f zipick-backend/db/infra-init.sql
--
-- [경고] 기존 인프라 테이블을 DROP 하므로 수집해 둔 데이터가 지워진다. 로컬에서만 사용한다.
--        데이터가 지워져도 서버를 띄우면 스케줄러가 다시 수집한다.
--
-- 담당: 주변 인프라 (한채희). 엔티티가 바뀌면 이 파일도 함께 갱신한다.
-- =============================================================================

DROP TABLE IF EXISTS housing_infra_place;
DROP TABLE IF EXISTS housing_infra_snapshot;

-- 주택 한 채의 수집 스냅샷. 이 행이 있으면 policy_signature 의 모든 카테고리를 정상 조회한 것이다.
create table housing_infra_snapshot (
    housing_infra_snapshot_id bigint generated by default as identity,
    housing_id bigint not null,
    policy_signature varchar(500) not null,
    collected_latitude decimal(10,7) not null,
    collected_longitude decimal(10,7) not null,
    nearest jsonb,
    collected_at timestamp(6) with time zone not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (housing_infra_snapshot_id),
    constraint uk_housing_infra_snapshot_housing unique (housing_id),
    constraint fk_housing_infra_snapshot_housing foreign key (housing_id)
        references housing (housing_id) on delete cascade
);

-- 카테고리별 '가장 가까운 시설' 1곳. 반경 내 결과가 0건인 카테고리는 행이 없다.
-- search_count 는 저장 행 수가 아니라 카카오 meta.total_count(반경 내 전체 시설 수)다.
create table housing_infra_place (
    housing_infra_place_id bigint generated by default as identity,
    housing_infra_snapshot_id bigint not null,
    search_count integer not null,
    distance_meter integer not null,
    latitude decimal(10,7),
    longitude decimal(10,7),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    category_code varchar(30) not null,
    kakao_place_id varchar(50),
    name varchar(255) not null,
    road_address varchar(500),
    address varchar(500),
    place_url varchar(2000),
    primary key (housing_infra_place_id),
    constraint uk_housing_infra_place_category unique (housing_infra_snapshot_id, category_code),
    constraint fk_housing_infra_place_snapshot foreign key (housing_infra_snapshot_id)
        references housing_infra_snapshot (housing_infra_snapshot_id) on delete cascade,
    constraint ck_housing_infra_place_distance check (distance_meter >= 0),
    constraint ck_housing_infra_place_search_count check (search_count >= 0)
);

-- 만료 대상(TTL) 조회용
create index idx_housing_infra_snapshot_collected_at on housing_infra_snapshot (collected_at);
-- 주택 상세 조회 시 카테고리 묶음을 한 번에 읽는다
create index idx_housing_infra_place_snapshot_id on housing_infra_place (housing_infra_snapshot_id);
