-- 운영자 화면(/admin) 전용 테이블. 로컬: local-init.sql 뒤에 실행. 운영: 그대로 적용 (모두 신규 테이블, 기존 데이터 영향 없음)
-- ddl-auto 가 validate 라 엔티티(com.zipick.admin.*)와 컬럼이 어긋나면 서버가 뜨지 않는다.

-- 수집기 프로세스 실행 기록. 수집기 진입점(batch/*Application)이 시작·종료 때 남긴다
create table if not exists collection_run (
    collection_run_id bigint generated by default as identity,
    job_type varchar(20) not null check (job_type in ('BASIC','AI','INFRA','FULL')),
    trigger_type varchar(20) not null,
    request_id bigint,
    status varchar(20) not null check (status in ('RUNNING','SUCCESS','FAILED')),
    started_at timestamp(6) with time zone not null,
    ended_at timestamp(6) with time zone,
    summary jsonb,
    error_message text,
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (collection_run_id)
);
create index if not exists idx_collection_run_job_started on collection_run (job_type, started_at desc);

-- 운영자 화면의 수동 실행 요청. deploy/monitoring/run-requested-collection.sh (cron 1분) 가 PENDING 을 집어 실행한다
create table if not exists collection_request (
    collection_request_id bigint generated by default as identity,
    job_type varchar(20) not null check (job_type in ('BASIC','AI','INFRA','FULL')),
    status varchar(20) not null check (status in ('PENDING','RUNNING','DONE','FAILED','CANCELLED')),
    requested_by bigint not null,
    note varchar(200),
    started_at timestamp(6) with time zone,
    finished_at timestamp(6) with time zone,
    result_message varchar(500),
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (collection_request_id)
);
create index if not exists idx_collection_request_status on collection_request (status);

-- Gemini PDF 추출이 미완료·빈 결과·예외로 끝난 첨부문서 (문서 키당 한 행, 성공하면 삭제)
create table if not exists ai_document_issue (
    ai_document_issue_id bigint generated by default as identity,
    document_key varchar(700) not null,
    agency varchar(50),
    notice_title varchar(500),
    file_name varchar(500),
    reason varchar(20) not null,
    expected_units integer,
    parsed_units integer,
    detail text,
    occurrences integer not null default 0,
    first_seen_at timestamp(6) with time zone not null,
    last_seen_at timestamp(6) with time zone not null,
    acknowledged boolean not null default false,
    acknowledged_by bigint,
    admin_note varchar(500),
    created_at timestamp(6),
    updated_at timestamp(6),
    primary key (ai_document_issue_id),
    constraint uk_ai_document_issue_key unique (document_key)
);
create index if not exists idx_ai_document_issue_open on ai_document_issue (acknowledged, last_seen_at desc);

-- 사용자 행동 기록 (화면 진입·클릭·로그인). 프론트가 묶어 보내고, 운영자 화면 "사용자 행동" 에서 본다. 90일 뒤 자동 삭제
create table if not exists user_activity (
    user_activity_id bigint generated by default as identity,
    user_id bigint,
    anonymous_id varchar(64),
    ip varchar(64),
    user_agent varchar(300),
    event_type varchar(20) not null,
    path varchar(500) not null,
    label varchar(200),
    target varchar(200),
    occurred_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    primary key (user_activity_id)
);
create index if not exists idx_user_activity_user_time on user_activity (user_id, occurred_at desc);
create index if not exists idx_user_activity_anon_time on user_activity (anonymous_id, occurred_at desc);
create index if not exists idx_user_activity_time on user_activity (occurred_at desc);
create index if not exists idx_user_activity_ip on user_activity (ip);
