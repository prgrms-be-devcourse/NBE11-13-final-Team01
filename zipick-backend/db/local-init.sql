-- =============================================================================
-- ZIPICK 로컬 개발용 스키마 초기화 DDL
-- =============================================================================
--
-- [경고] 이 스크립트는 기존 테이블을 DROP 하므로 저장된 데이터가 모두 삭제된다.
--        로컬 개발 환경에서만 실행한다. 운영 DB(RDS 등)에는 절대 적용하지 않는다.
--
-- 사용 방법
--   1. 로컬 PostgreSQL에 zipick 데이터베이스가 있어야 한다.
--        CREATE DATABASE zipick;
--   2. 스키마가 바뀌면 이 파일을 다시 실행해 초기화한다.
--        psql -U {사용자명} -d zipick -f zipick-backend/db/local-init.sql
--   3. 애플리케이션을 실행해 ddl-auto: validate 검증을 통과하는지 확인한다.
--
-- 관리 규칙
--   - 엔티티가 추가·변경되면 이 파일도 함께 갱신해 커밋한다.
--   - hibernate 의 create-drop 설정은 사용하지 않는다.
--
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. DROP : 자식 테이블부터 삭제해 FK 제약 충돌을 피한다.
-- -----------------------------------------------------------------------------

DROP TABLE IF EXISTS notification_cursors;
DROP TABLE IF EXISTS interest_notices;
DROP TABLE IF EXISTS refresh_token;
DROP TABLE IF EXISTS recommendation_pair_choices;
DROP TABLE IF EXISTS recommendation_feedbacks;
DROP TABLE IF EXISTS recommendation_profiles;
DROP TABLE IF EXISTS user_preferences;
DROP TABLE IF EXISTS user_profiles;
DROP TABLE IF EXISTS users;


-- -----------------------------------------------------------------------------
-- 2. CREATE : 참조 대상 테이블부터 생성한다.
-- -----------------------------------------------------------------------------

-- Hibernate(PostgreSQLDialect)가 엔티티에서 만든 DDL을 기준으로 작성했다. ddl-auto: validate 와 일치한다.
-- 엔티티를 바꾸면 아래처럼 다시 뽑아 교체한다 (DB 연결 없이 동작).
--   DB_USERNAME=none DB_PASSWORD=none ./gradlew bootRun --args="--spring.jpa.hibernate.ddl-auto=none \
--     --spring.jpa.properties.hibernate.dialect=org.hibernate.dialect.PostgreSQLDialect \
--     --spring.jpa.properties.hibernate.boot.allow_jdbc_metadata_access=false \
--     --spring.jpa.properties.jakarta.persistence.schema-generation.scripts.action=create \
--     --spring.jpa.properties.jakarta.persistence.schema-generation.scripts.create-target=build/ddl/create.sql \
--     --spring.jpa.properties.hibernate.hbm2ddl.delimiter=; --spring.jpa.properties.hibernate.format_sql=true"
--
-- 테이블 담당: users·refresh_token = 인증, user_profiles·user_preferences·recommendation_* = 추천.
--             공고·주택(notice·housing·housing_supply 등)은 notice-init.sql 에서 만든다. 추천은 그 테이블을 읽기만 한다.

create table recommendation_feedbacks (
    created_at timestamp(6),
    housing_id bigint not null,
    id bigint generated by default as identity,
    updated_at timestamp(6),
    user_id bigint not null,
    type varchar(10) not null check ((type in ('HIDE','DISLIKE'))),
    reason varchar(20) check ((reason in ('EXPENSIVE','REGION','SMALL','OLD','INFRA','ETC'))),
    primary key (id)
);

create table recommendation_pair_choices (
    created_at timestamp(6),
    id bigint generated by default as identity,
    left_house_id bigint not null,
    right_house_id bigint not null,
    updated_at timestamp(6),
    user_id bigint not null,
    choice varchar(10) not null,
    primary key (id)
);

create table recommendation_profiles (
    active boolean not null,
    version integer not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    user_id bigint not null,
    name varchar(30) not null,
    infra_weights text,
    rules text,
    weights text not null,
    primary key (id)
);
create table user_preferences (
    area_max numeric(6,2),
    area_min numeric(6,2),
    deposit_max integer,
    monthly_budget integer,
    rent_max integer,
    rooms_min integer,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    user_id bigint not null,
    housing_types text,
    regions text not null,
    rental_types text,
    primary key (id)
);
create table user_profiles (
    birth_date date not null,
    car_value integer,
    homeless boolean not null,
    household_size integer not null,
    married boolean not null,
    monthly_income integer,
    total_assets integer,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    user_id bigint not null,
    student_status varchar(20) check ((student_status in ('NONE','UNIVERSITY','JOB_SEEKER'))),
    primary key (id)
);

create table users (
    created_at timestamp(6),
    updated_at timestamp(6),
    user_id bigint generated by default as identity,
    email varchar(255) not null,
    password varchar(255) not null,
    role varchar(30) not null,
    primary key (user_id)
);

create table refresh_token (
    created_at timestamp(6),
    updated_at timestamp(6),
    expires_at timestamp(6) not null,
    refresh_token_id bigint generated by default as identity,
    user_id bigint not null,
    token varchar(512) not null,
    primary key (refresh_token_id)
);

create index idx_rec_feedback_user
   on recommendation_feedbacks (user_id);

create index idx_rec_pair_user
   on recommendation_pair_choices (user_id);

create index idx_rec_profile_user
   on recommendation_profiles (user_id);

alter table user_preferences
   add constraint UKqy8dkrkc8b34dcgwoq2km43rd unique (user_id);

alter table user_profiles
   add constraint UKe5h89rk3ijvdmaiig4srogdc6 unique (user_id);

alter table users
   add constraint uk_users_email unique (email);

-- 사전 입력정보는 사용자에 종속된다. 없는 사용자로 저장되는 것을 DB에서 막는다.
-- 엔티티는 Long userId 를 그대로 쓴다 (ddl-auto: validate 는 FK 제약을 검증하지 않는다).
alter table user_profiles
   add constraint fk_user_profiles_user
   foreign key (user_id)
   references users (user_id);

alter table user_preferences
   add constraint fk_user_preferences_user
   foreign key (user_id)
   references users (user_id);

alter table refresh_token
   add constraint uk_refresh_token_user_id unique (user_id);

alter table refresh_token
   add constraint fk_refresh_token_user
   foreign key (user_id)
   references users (user_id)
   on delete cascade;


-- -----------------------------------------------------------------------------
-- 3. 관심 공고 · 알림 (안서호)
--    interest_notices    : 사용자가 ☆로 저장한 공고. 일정(캘린더)은 notice 의 날짜를 그대로 읽는다
--    notification_cursors : 스케줄러가 어디까지 봤는지 (NEW_MATCH = 마지막으로 확인한 공고 수집 시각)
--    알림 설정·아웃박스는 알림센터(zipick-notification, DB zipick_notification)로 옮겨 갔다 (2026-10-20).
--    기존 DB 는 DROP TABLE notification_settings, notification_events; 만 실행하면 된다.
-- -----------------------------------------------------------------------------

create table interest_notices (
    created_at timestamp(6),
    id bigint generated by default as identity,
    notice_id bigint not null,
    updated_at timestamp(6),
    user_id bigint not null,
    memo varchar(200),
    primary key (id)
);

create table notification_cursors (
    checked_at timestamp(6) not null,
    name varchar(50) not null,
    primary key (name)
);

create index idx_interest_user
   on interest_notices (user_id);

alter table interest_notices
   add constraint uk_interest_user_notice unique (user_id, notice_id);

alter table interest_notices
   add constraint fk_interest_notices_user
   foreign key (user_id)
   references users (user_id);
