-- =============================================================================
-- ZIPICK AI 맞춤 신청 준비 가이드 테이블 추가 DDL
-- =============================================================================
--
-- [다른 init 스크립트와 목적이 다르다]
--   local-init.sql / notice-init.sql / infra-init.sql 은 "로컬 전체 초기화" 용도라
--   DROP TABLE 로 시작한다. 이 파일은 그렇지 않다.
--
--   이 파일은 <b>기존 데이터를 그대로 둔 채 새 테이블만 추가</b>하기 위한 것이다.
--   저장되는 내용이 AI 호출 결과이고, 한 번 지우면 무료 사용량을 다시 써서
--   만들어야 하기 때문에 재실행으로 지워지면 안 된다.
--   그래서 DROP 없이 IF NOT EXISTS 로만 만든다. 여러 번 실행해도 안전하다.
--
--   테이블을 정말 비우고 싶으면 이 파일을 고치지 말고 직접 실행한다.
--     DROP TABLE IF EXISTS notice_application_guide;
--
-- [실행 순서] local-init.sql → notice-init.sql → infra-init.sql → guide-init.sql
--   users(local-init) 와 notice(notice-init) 를 모두 참조하므로 두 파일 뒤에 실행한다.
--
--   psql -U {사용자명} -d zipick -f zipick-backend/db/guide-init.sql
--
-- [배포] 운영 DB 는 볼륨이 이미 있어 초기화 스크립트가 자동 재실행되지 않는다.
--        배포 때 이 파일을 한 번 직접 실행해야 한다. (배포 체크리스트 참고)
--
-- 담당: AI 신청 준비 가이드 (한채희). 엔티티가 바뀌면 이 파일도 함께 갱신한다.
-- =============================================================================

-- 사용자 한 명이 공고 하나에 대해 받은 AI 신청 준비 가이드. (user_id, notice_id) 당 1행.
-- 결과가 사용자 상황에 따라 달라지므로 캐시 단위도 user + notice 다. 이력은 남기지 않는다.
--
-- prompt_version / reducer_version / model / profile_updated_at 이 모두 현재 값과 같으면
-- 저장된 결과를 그대로 돌려주고 Gemini 를 호출하지 않는다.
create table if not exists notice_application_guide (
    notice_application_guide_id bigint generated by default as identity,
    user_id bigint not null,
    notice_id bigint not null,
    -- GuideResult(summary / personalChecks / documents / cautions) 직렬화. 안을 조회하지 않고 통째로 쓴다
    result_json jsonb not null,
    -- {"S1":{"fileName":"모집공고.pdf","page":24}} 공고문 출처 표시용
    sources_json jsonb not null,
    prompt_version varchar(50) not null,
    reducer_version varchar(50) not null,
    model varchar(100) not null,
    -- 생성 당시 user_profiles.updated_at 복사본. 사용자가 내 정보를 고치면 그 사람 것만 다시 만든다
    profile_updated_at timestamp(6) not null,
    generated_at timestamp(6) not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (notice_application_guide_id),
    constraint uk_notice_application_guide_user_notice unique (user_id, notice_id),
    constraint fk_notice_application_guide_user
        foreign key (user_id) references users (user_id) on delete cascade,
    constraint fk_notice_application_guide_notice
        foreign key (notice_id) references notice (notice_id) on delete cascade
);

-- 오늘 만든 건수를 세어 무료 사용량 상한을 확인한다
create index if not exists idx_notice_application_guide_generated_at
    on notice_application_guide (generated_at);
